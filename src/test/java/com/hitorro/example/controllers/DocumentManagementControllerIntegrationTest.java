    @Test
    @Order(8)
    @DisplayName("Create version - should create new version of document")
    void testCreateVersion() {
        if (controller == null || createdDocumentId == null) {
            System.out.println("Skipping - prerequisites not met");
            return;
        }
        
        VersionRequest request = new VersionRequest();
        request.setNote("Version 1.1 created by integration test");
        
        ResponseEntity<DocumentResponse> response = 
                controller.createVersion(createdDocumentId, request);
        
        assertEquals(HttpStatus.CREATED, response.getStatusCode());
        
        DocumentResponse newVersion = response.getBody();
        assertNotNull(newVersion);
        assertNotEquals(createdDocumentId, newVersion.getId(), 
                       "New version should have different ID");
        assertEquals(createdDocumentId, newVersion.getCanonicalId(),
                    "New version should reference original as canonical");
        
        System.out.println("✓ Created version: " + newVersion.getVersionLabel());
    }
    
