    @Test
    @Order(6)
    @DisplayName("Query documents - should find by title")
    void testQueryDocuments() {
        if (controller == null || createdDocumentId == null) {
            System.out.println("Skipping - prerequisites not met");
            return;
        }
        
        QueryRequest request = new QueryRequest();
        request.setTitle("Integration Test");
        request.setMaxResults(10);
        
        ResponseEntity<List<DocumentResponse>> response = controller.queryDocuments(request);
        
        assertEquals(HttpStatus.OK, response.getStatusCode());
        
        List<DocumentResponse> documents = response.getBody();
        assertNotNull(documents);
        assertTrue(documents.size() > 0, "Should find at least one document");
        
        // Check our document is in the results
        boolean found = documents.stream()
                .anyMatch(d -> d.getId().equals(createdDocumentId));
        assertTrue(found, "Created document should be in query results");
        
        System.out.println("✓ Query found " + documents.size() + " document(s)");
    }
    
